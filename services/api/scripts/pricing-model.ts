/**
 * Margin model, computed from the live catalogue (plans, prices, credit costs, model prices):
 *   pnpm --filter @prompttoppt/api pricing:model > ../../docs/PRICING_MODEL.md
 * Change a price/credit/tier in the DB, re-run, and see the profit impact BEFORE shipping it.
 */
import { eq } from 'drizzle-orm'
import { db, pool } from '../src/db/index.ts'
import { creditCost, modelCatalog, plan, planPrice } from '../src/db/schema.ts'

const FX = Number(process.env['INR_PER_USD'] ?? 88) // ASSUMPTION — set to today's rate
const GST = 0.18 // ASSUMPTION: India prices are GST-inclusive (if they're ex-GST, margins in India are 18% better)
const TOK = { inPerSlide: 310, outPerSlide: 300 } // measured on real decks (8 slides ≈ 2.5k in / 2.4k out incl. analysis + outline)
const TYPICAL = 0.25 // typical share of the monthly allowance a paying user actually spends (breakage assumption)

const net = (gross: number, currency: 'USD' | 'INR') => {
  if (currency === 'USD') return gross - (gross * 0.029 + 0.3) // Stripe 2.9% + $0.30
  const exGst = gross / (1 + GST)
  const fee = gross * 0.02 * (1 + GST) // Razorpay ~2% + GST on the fee
  return (exGst - fee) / FX // → USD
}
const usd = (n: number) => `$${n < 0.01 ? n.toFixed(5) : n < 1 ? n.toFixed(4) : n.toFixed(2)}`
const pct = (n: number) => `${(n * 100).toFixed(0)}%`

const [plans, prices, costs, models] = await Promise.all([
  db.select().from(plan).orderBy(plan.sortOrder), db.select().from(planPrice), db.select().from(creditCost), db.select().from(modelCatalog).where(eq(modelCatalog.enabled, true)),
])
const credits = (action: string, tier: string) => costs.find((c) => c.action === action && c.tier === tier)?.credits ?? 0
const slideModels = models.filter((m) => m.kind === 'text' && m.provider === 'openrouter')
const imageModels = models.filter((m) => m.kind === 'image' && m.provider === 'openrouter')
const costPerSlide = (m: (typeof models)[number]) => (TOK.inPerSlide * Number(m.inputPerMTokUsd) + TOK.outPerSlide * Number(m.outputPerMTokUsd)) / 1e6

console.log(`# Pricing & margin model

_Generated by \`pnpm --filter @prompttoppt/api pricing:model\` from the live catalogue. Assumptions: **${FX} INR/USD**, India prices **GST-inclusive (${GST * 100}%)**, Stripe 2.9% + $0.30, Razorpay ~2% + GST on fee, ${TOK.inPerSlide} in / ${TOK.outPerSlide} out tokens per slide (measured), typical utilisation ${pct(TYPICAL)}. Provider costs are OpenRouter list prices (production catalogue). Vertex/AI Studio local-dev costs are estimates._

## Net revenue per paying user (after tax & payment fees)
| Plan | Market | Price | Net / month | Credits | Net per credit |
|---|---|---|---|---|---|`)
type Row = { plan: string; market: string; revPerCredit: number; net: number; credits: number }
const rows: Row[] = []
for (const p of plans.filter((x) => x.id !== 'starter')) {
  for (const cur of ['USD', 'INR'] as const) {
    for (const interval of ['month', 'year'] as const) {
      const pr = prices.find((x) => x.planId === p.id && x.currency === cur && x.interval === interval)
      if (!pr) continue
      const gross = (interval === 'year' ? pr.amountMinor / 12 : pr.amountMinor) / 100
      const n = net(gross, cur)
      const label = `${cur === 'USD' ? '$' : '₹'}${gross.toLocaleString('en-US', { maximumFractionDigits: 0 })}/mo${interval === 'year' ? ' (annual plan)' : ''}`
      console.log(`| ${p.name} | ${cur === 'INR' ? 'India' : 'International'} | ${label} | ${usd(n)} | ${p.monthlyCredits.toLocaleString()} | ${usd(n / p.monthlyCredits)} |`)
      if (interval === 'year') rows.push({ plan: p.id, market: cur, revPerCredit: n / p.monthlyCredits, net: n, credits: p.monthlyCredits })
    }
  }
}
const worstRows = rows // worst case = cheapest realised price = annual
console.log(`\n_Margin tables use the **annual-plan** price (the lowest revenue per credit) as the binding case._\n`)

const tierOf = (id: string) => plans.find((p) => p.id === id)!
console.log(`## Text generation — worst case (user spends the WHOLE allowance on that model) and typical (${pct(TYPICAL)})
| Model | Tier | Credits/slide | Cost/slide | Cost per credit | ${worstRows.map((r) => `${r.plan} ${r.market} worst`).join(' | ')} |
|---|---|---|---|---|${worstRows.map(() => '---|').join('')}`)
for (const m of slideModels) {
  const cps = costPerSlide(m)
  const cr = credits('generate_slide', m.accessTier)
  const costPerCredit = cps / cr
  const cells = worstRows.map((r) => {
    const allowed = tierOf(r.plan).features.modelTiers.includes(m.accessTier as never)
    if (!allowed) return 'n/a (not in plan)'
    const worst = costPerCredit * r.credits
    return `${usd(worst)} → **${pct(1 - worst / r.net)}**`
  })
  console.log(`| ${m.displayName} | ${m.accessTier} | ${cr} | ${usd(cps)} | ${usd(costPerCredit)} | ${cells.join(' | ')} |`)
}
console.log(`\n## AI images
| Model | Tier | Credits/image | Est. cost/image | ${worstRows.map((r) => `${r.plan} ${r.market}: margin if allowance fully spent on this`).join(' | ')} |
|---|---|---|---|${worstRows.map(() => '---|').join('')}`)
for (const m of imageModels) {
  const cr = credits('image', m.accessTier)
  const c = Number(m.perImageUsd)
  const cells = worstRows.map((r) => {
    if (!tierOf(r.plan).features.modelTiers.includes(m.accessTier as never)) return 'n/a (not in plan)'
    const images = Math.min(Math.floor(r.credits / cr), tierOf(r.plan).maxImagesPerMonth)
    const spend = images * c
    return `${images} imgs (cap ${tierOf(r.plan).maxImagesPerMonth}) = ${usd(spend)} → **${pct(1 - spend / r.net)}**`
  })
  console.log(`| ${m.displayName} | ${m.accessTier} | ${cr} | ${usd(c)} | ${cells.join(' | ')} |`)
}

const starter = tierOf('starter')
const sm = slideModels.filter((m) => m.accessTier === 'starter').sort((a, b) => costPerSlide(b) - costPerSlide(a))[0]
const im = imageModels.find((m) => m.accessTier === 'starter')
console.log(`
## Free tier (Starter) — what a free user can cost us per month
- ${starter.monthlyCredits} credits. Worst case if ALL on the costliest starter text model (${sm?.displayName}): ${usd((costPerSlide(sm!) / credits('generate_slide', 'starter')) * starter.monthlyCredits)}.
- Images are capped at ${starter.maxImagesPerMonth}/month (${starter.maxImagesPerPresentation}/deck) → at most ${usd(starter.maxImagesPerMonth * Number(im?.perImageUsd ?? 0))}/month.
- No export, watermark on → no incentive to farm accounts for deliverables.

## How to read this
- "**margin**" = 1 − worst-case provider spend ÷ net revenue. Negative = loses money if that user maxes out; real users spend far less (typical ${pct(TYPICAL)} → multiply spend by ${TYPICAL}).
- The Opus-class models ($5/$25) are in **Gold only** because at 5 credits/slide they lose money on India Pro; flip a row in \`model_catalog\` and re-run this script to test alternatives.
- Levers when a row looks thin: raise credits/slide or credits/image (\`credit_cost\`), lower plan credits (\`plan.monthly_credits\`), lower image caps (\`plan.max_images_per_month\`), or move a model to a higher tier — all database edits.
`)
await pool.end()
