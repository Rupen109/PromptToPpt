/**
 * Whole-app load test (dev only). Plan: docs/FULL_SECURITY_LOAD_CTA_TEST_PLAN.md (E1–E5).
 * Run against PRODUCTION builds: website `next start` (WEB), API `node dist/index.js` started with TRUSTED_PROXY_HOPS=1 (so each virtual user can have its own address).
 *   tsx --env-file-if-exists=.env scripts/load-app.ts            env: WEB=http://localhost:3100 API=http://localhost:4000 ORIGIN=http://localhost:3001
 *   STAGES=100,500,1000,2000,3000  HOLD_S=30  RAMP_S=10  PROCS=4  USERS=500  SPIKE=1
 * Mix: 60 % visitors (website pages + plans), 30 % editors (session, decks, open, autosave, comments), 10 % viewers of a shared link (view + analytics).
 * The load is generated by PROCS child processes so the generator itself is not the bottleneck (its own event-loop lag is reported).
 */
import { fork, execSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { monitorEventLoopDelay } from 'node:perf_hooks'
import { isProd } from '../src/env.ts'

if (isProd) { console.error('Refusing to run in production'); process.exit(1) }
const WEB = process.env['WEB'] ?? 'http://localhost:3100'
const API = process.env['API'] ?? 'http://localhost:4000'
const ORIGIN = process.env['ORIGIN'] ?? 'http://localhost:3001'
const STAGES = (process.env['STAGES'] ?? '100,500,1000,2000,3000').split(',').map(Number)
const HOLD_S = Number(process.env['HOLD_S'] ?? 30), RAMP_S = Number(process.env['RAMP_S'] ?? 10)
const PROCS = Number(process.env['PROCS'] ?? 4), USERS = Number(process.env['USERS'] ?? 500)
const SPIKE = process.env['SPIKE'] !== '0'
const USERS_FILE = '/private/tmp/claude-502/load-app-users.json'
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms))
const rnd = () => Math.random().toString(36).slice(2, 10)
const pct = (a: number[], p: number) => (a.length ? [...a].sort((x, y) => x - y)[Math.min(a.length - 1, Math.floor((a.length * p) / 100))]! : 0)

interface Fixture { cookie: string; deckId: string }
interface Fixtures { users: Fixture[]; shareTokens: string[]; slideIds: string[][] }

// ═════════════════ worker: runs its share of the virtual users ═════════════════
async function worker() {
  const fx = JSON.parse(readFileSync(USERS_FILE, 'utf8')) as Fixtures
  const samples: [string, number, number, number][] = [] // class, status, ms, stageIdx
  let stage = 0
  let gen = 0, ended = false
  const alive = (g: number) => g === gen && !ended
  const lag = monitorEventLoopDelay({ resolution: 20 }); lag.enable()
  const ip = () => `10.${Math.floor(Math.random() * 250)}.${Math.floor(Math.random() * 250)}.${1 + Math.floor(Math.random() * 250)}`
  async function req(cls: string, url: string, init: RequestInit = {}): Promise<{ status: number; json: any }> {
    const t0 = performance.now()
    try {
      const r = await fetch(url, { ...init, signal: AbortSignal.timeout(30_000) })
      const text = await r.text()
      samples.push([cls, r.status, performance.now() - t0, stage])
      let json: any = null; if (r.headers.get('content-type')?.includes('json')) { try { json = JSON.parse(text) } catch { /* */ } }
      return { status: r.status, json }
    } catch { samples.push([cls, 0, performance.now() - t0, stage]); return { status: 0, json: null } }
  }
  const think = (a: number, b: number) => sleep(a + Math.random() * (b - a))

  async function visitor(g: number) {
    const addr = ip(); const pages = ['/', '/pricing', '/templates', '/free-tools', '/templates/pitch-launchpad', '/login', '/signup', '/free-templates/sales-presentation-templates']
    while (alive(g)) {
      const path = pages[Math.floor(Math.random() * pages.length)]!
      await req('web-page', WEB + path, { headers: { 'X-Forwarded-For': addr } })
      if (path === '/pricing') await req('api-read', `${API}/api/v1/plans`, { headers: { 'X-Forwarded-For': addr, Origin: ORIGIN } })
      await think(1000, 5000)
    }
  }
  async function editor(i: number, g: number) {
    const u = fx.users[i % fx.users.length]!; const addr = ip()
    const H = { Cookie: u.cookie, Origin: ORIGIN, 'X-Forwarded-For': addr, 'Content-Type': 'application/json' }
    await req('api-read', `${API}/api/auth/get-session`, { headers: H })
    await req('api-read', `${API}/api/v1/me`, { headers: H })
    await req('api-read', `${API}/api/v1/me/entitlements`, { headers: H })
    await req('api-read', `${API}/api/v1/presentations`, { headers: H })
    let d = (await req('api-read', `${API}/api/v1/presentations/${u.deckId}`, { headers: H })).json?.data
    let rev: number = d?.revision ?? 1
    let n = 0
    while (alive(g)) {
      await think(2500, 6000)
      if (d && Math.random() < 0.7) {
        const doc = d.document ?? d
        const body = { baseRevision: rev, document: { ...doc, title: `Load ${n++ % 2 ? 'A' : 'B'}` } }
        const r = await req('api-write', `${API}/api/v1/presentations/${u.deckId}`, { method: 'PUT', headers: H, body: JSON.stringify(body) })
        if (r.status === 200) rev = r.json?.data?.revision ?? rev + 1
        else if (r.status === 409 || r.status === 428) { d = (await req('api-read', `${API}/api/v1/presentations/${u.deckId}`, { headers: H })).json?.data; rev = d?.revision ?? rev }
      }
      if (Math.random() < 0.4) await req('api-read', `${API}/api/v1/presentations/${u.deckId}/comments`, { headers: H })
      if (Math.random() < 0.08) {
        const slideId = (d?.document ?? d)?.slides?.[0]?.id
        if (slideId) await req('api-write', `${API}/api/v1/presentations/${u.deckId}/comments`, { method: 'POST', headers: H, body: JSON.stringify({ slideId, body: 'load test comment' }) })
      }
      if (Math.random() < 0.2) await req('api-read', `${API}/api/v1/presentations`, { headers: H })
    }
  }
  async function viewer(i: number, g: number) {
    const token = fx.shareTokens[i % fx.shareTokens.length]!; const slides = fx.slideIds[i % fx.slideIds.length]!
    const addr = ip(); const vid = rnd() + rnd()
    const H = { 'X-Forwarded-For': addr, 'Content-Type': 'application/json', Origin: ORIGIN, 'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64) Chrome/120 Safari/537.36' }
    while (alive(g)) {
      await req('public-view', `${API}/api/v1/public/share/${token}`, { headers: H })
      const st = await req('public-write', `${API}/api/v1/public/share/${token}/analytics/start`, { method: 'POST', headers: H, body: JSON.stringify({ vid, vw: 1280 }) })
      const viewId = st.json?.data?.viewId
      for (let k = 0; k < 3 && alive(g); k++) {
        await think(4000, 8000)
        if (viewId && slides[0]) await req('public-write', `${API}/api/v1/public/share/${token}/analytics/ping`, { method: 'POST', headers: { ...H, 'Content-Type': 'text/plain' }, body: JSON.stringify({ viewId, vid, slides: [{ id: slides[0], ms: 3000 }] }) })
      }
      await think(2000, 6000)
    }
  }
  let started = 0
  const launch = (n: number) => { for (let k = 0; k < n; k++) { const i = started++; const r = i % 10; const g = gen; void (r < 6 ? visitor(g) : r < 9 ? editor(i, g) : viewer(i, g)) } }

  process.on('message', async (m: any) => {
    if (m.type === 'target') { stage = m.stage; const add = m.target - started; const step = Math.max(1, Math.ceil(add / Math.max(1, m.rampMs / 200))); const end = Date.now() + m.rampMs; while (started < m.target) { launch(Math.min(step, m.target - started)); if (Date.now() > end) { launch(m.target - started); break }; await sleep(200) } }
    if (m.type === 'stage') stage = m.stage
    if (m.type === 'shrink') { gen++; stage = m.stage; started = 0; launch(m.keep) /* the old loops end within their think time */ }
    if (m.type === 'end') { ended = true; await sleep(1500); const file = `/private/tmp/claude-502/load-child-${process.pid}.json`; writeFileSync(file, JSON.stringify(samples)); process.send!({ type: 'result', file, lagMeanMs: lag.mean / 1e6, lagP99Ms: lag.percentile(99) / 1e6, lagMaxMs: lag.max / 1e6 }, () => process.exit(0)) }
  })
  process.on('uncaughtException', (e) => { console.error('worker crash:', e); process.exit(1) })
  process.on('unhandledRejection', (e) => { console.error('worker rejection:', e) })
  process.send!({ type: 'ready' })
}

// ═════════════════ parent ═════════════════
async function setup(): Promise<void> {
  if (existsSync(USERS_FILE)) {
    const f = JSON.parse(readFileSync(USERS_FILE, 'utf8')) as Fixtures
    const ok = f.users.length >= USERS && (await fetch(`${API}/api/v1/me`, { headers: { Cookie: f.users[0]!.cookie } })).status === 200
    if (ok) { console.log(`reusing ${f.users.length} saved users`); return }
  }
  const { auth } = await import('../src/auth.ts')
  console.log(`creating ${USERS} users + decks (in-process, bypassing the sign-up guard)…`)
  const users: Fixture[] = []
  const conc = 8
  let next = 0
  await Promise.all(Array.from({ length: conc }, async () => {
    while (next < USERS) {
      const i = next++
      const email = `load${Date.now().toString(36)}${i}${rnd()}@example.com`
      const res = await auth.api.signUpEmail({ body: { email, password: 'Passw0rd!load-test', name: `Load ${i}` }, asResponse: true })
      const cookie = res.headers.getSetCookie().map((c) => c.split(';')[0]).join('; ')
      const H = { Cookie: cookie, Origin: ORIGIN, 'Content-Type': 'application/json' }
      const d = await (await fetch(`${API}/api/v1/presentations`, { method: 'POST', headers: H, body: JSON.stringify({ title: `Load deck ${i}` }) })).json() as any
      users[i] = { cookie, deckId: d.data.id }
    }
  }))
  const shareTokens: string[] = [], slideIds: string[][] = []
  for (const u of users.slice(0, 40)) {
    const H = { Cookie: u.cookie, Origin: ORIGIN, 'Content-Type': 'application/json' }
    const s = await (await fetch(`${API}/api/v1/presentations/${u.deckId}/share`, { method: 'POST', headers: H, body: '{}' })).json() as any
    const tok = s?.data?.url?.split('/s/')[1]; if (!tok) continue
    const v = await (await fetch(`${API}/api/v1/public/share/${tok}`)).json() as any
    shareTokens.push(tok); slideIds.push(((v.data?.document ?? v.data)?.slides ?? []).map((x: any) => x.id))
  }
  if (!shareTokens.length) throw new Error('no share links could be created (Starter plan has no sharing?)')
  writeFileSync(USERS_FILE, JSON.stringify({ users, shareTokens, slideIds } satisfies Fixtures))
  const { pool } = await import('../src/db/index.ts'); await pool.end()
}

const pidOn = (port: number) => { try { return Number(execSync(`lsof -iTCP:${port} -sTCP:LISTEN -t | head -1`).toString().trim()) } catch { return 0 } }
const proc = (pid: number) => { try { const [rss, cpu] = execSync(`ps -o rss=,pcpu= -p ${pid}`).toString().trim().split(/\s+/).map(Number); return { rssMb: Math.round(rss! / 1024), cpu: cpu! } } catch { return { rssMb: 0, cpu: 0 } } }

async function parent() {
  await setup()
  const apiPid = pidOn(Number(new URL(API).port)), webPid = pidOn(Number(new URL(WEB).port))
  const pg = new (await import('pg')).default.Client({ connectionString: process.env['DATABASE_URL'] }); await pg.connect()
  const kids = Array.from({ length: PROCS }, () => fork(new URL(import.meta.url).pathname, ['worker'], { execArgv: process.execArgv, env: process.env }))
  await Promise.all(kids.map((k) => new Promise<void>((r) => k.once('message', () => r()))))
  const results: any[] = []
  const done = Promise.all(kids.map((k, i) => new Promise<void>((r) => { k.on('message', (m: any) => { if (m.type === 'result') { results.push(m); r() } }); k.on('exit', (code, sig) => { console.log(`generator ${i} exited (code ${code}, signal ${sig})`); r() }) })))
  const sys: { stage: number; apiRss: number; apiCpu: number; webRss: number; webCpu: number; pgConns: number; canaryMs: number }[] = []
  let stageIdx = 0, sampling = true
  const sampler = (async () => { while (sampling) { const t0 = performance.now(); await fetch(`${API}/health`).catch(() => null); const canary = performance.now() - t0; const a = proc(apiPid), w = proc(webPid); const c = Number((await pg.query('select count(*) from pg_stat_activity').catch(() => ({ rows: [{ count: 0 }] }))).rows[0].count); sys.push({ stage: stageIdx, apiRss: a.rssMb, apiCpu: a.cpu, webRss: w.rssMb, webCpu: w.cpu, pgConns: c, canaryMs: canary }); await sleep(2000) } })()

  const plan: { label: string; target: number }[] = STAGES.map((t) => ({ label: `${t} users`, target: t }))
  if (SPIKE) { plan.push({ label: 'drop to 100', target: -100 }, { label: 'spike to 3000 (10x at once)', target: Math.max(...STAGES) }, { label: 'recovery at 100', target: -100 }) }
  console.log(`API pid ${apiPid}, website pid ${webPid}; ${PROCS} generator processes`)
  for (const [i, p] of plan.entries()) {
    stageIdx = i
    const target = Math.abs(p.target)
    const ramp = p.label.startsWith('spike') ? 2000 : RAMP_S * 1000
    if (p.target < 0) for (const k of kids) k.send({ type: 'shrink', keep: Math.ceil(target / PROCS), stage: i }), k.send({ type: 'stage', stage: i })
    else for (const k of kids) k.send({ type: 'target', target: Math.ceil(target / PROCS), stage: i, rampMs: ramp })
    console.log(`▶ stage ${i + 1}/${plan.length}: ${p.label}`)
    await sleep((ramp + HOLD_S * 1000))
  }
  sampling = false; await sampler
  for (const k of kids) k.send({ type: 'end' })
  await done
  await pg.end()

  const all = results.flatMap((r) => (r.file ? JSON.parse(readFileSync(r.file, 'utf8')) : []) as [string, number, number, number][])
  console.log('\n══ results per stage ══')
  const table: Record<string, unknown>[] = []
  const byStage: Record<string, number>[] = []
  for (const [i, p] of plan.entries()) {
    const s = all.filter((x) => x[3] === i)
    const dur = (HOLD_S + (p.label.startsWith('spike') ? 2 : RAMP_S)) || 1
    const cls = (c: string) => s.filter((x) => x[0] === c && x[1] > 0 && x[1] < 500).map((x) => x[2])
    const err = s.filter((x) => x[1] === 0 || x[1] >= 500).length, r429 = s.filter((x) => x[1] === 429).length
    const other4 = s.filter((x) => x[1] >= 400 && x[1] < 500 && x[1] !== 429).length
    const ss = sys.filter((x) => x.stage === i)
    const row = { stage: p.label, requests: s.length, rps: Math.round(s.length / dur), errors: err, errPct: +((100 * err) / Math.max(1, s.length)).toFixed(2), r429, other4xx: other4,
      'web p50/p95/p99': `${pct(cls('web-page'), 50).toFixed(0)}/${pct(cls('web-page'), 95).toFixed(0)}/${pct(cls('web-page'), 99).toFixed(0)}`,
      'apiRead p50/p95/p99': `${pct(cls('api-read'), 50).toFixed(0)}/${pct(cls('api-read'), 95).toFixed(0)}/${pct(cls('api-read'), 99).toFixed(0)}`,
      'apiWrite p50/p95/p99': `${pct(cls('api-write'), 50).toFixed(0)}/${pct(cls('api-write'), 95).toFixed(0)}/${pct(cls('api-write'), 99).toFixed(0)}`,
      'viewer p95': pct([...cls('public-view'), ...cls('public-write')], 95).toFixed(0),
      apiRssMb: Math.max(0, ...ss.map((x) => x.apiRss)), apiCpuMax: Math.max(0, ...ss.map((x) => x.apiCpu)), webCpuMax: Math.max(0, ...ss.map((x) => x.webCpu)), pgConnsMax: Math.max(0, ...ss.map((x) => x.pgConns)), canaryP95ms: +pct(ss.map((x) => x.canaryMs), 95).toFixed(0) }
    table.push(row); byStage.push({ errPct: row.errPct, ...Object.fromEntries([['p95read', pct(cls('api-read'), 95)], ['p95write', pct(cls('api-write'), 95)], ['p95web', pct(cls('web-page'), 95)]]) })
  }
  console.table(table)
  const statusCounts: Record<string, number> = {}
  for (const x of all) statusCounts[x[1]] = (statusCounts[x[1]] ?? 0) + 1
  console.log('status codes overall:', JSON.stringify(statusCounts))
  console.log('generator event-loop lag per process (mean/p99/max ms):', results.map((r) => `${r.lagMeanMs.toFixed(0)}/${r.lagP99Ms.toFixed(0)}/${r.lagMaxMs.toFixed(0)}`).join('  '))
  console.log(`API memory: start ${sys[0]?.apiRss} MB → end ${sys[sys.length - 1]?.apiRss} MB; website: ${sys[0]?.webRss} → ${sys[sys.length - 1]?.webRss} MB`)
  writeFileSync('/private/tmp/claude-502/load-app-result.json', JSON.stringify({ table, statusCounts, sys }, null, 1))
  process.exit(0)
}

if (process.argv[2] === 'worker') await worker(); else await parent()
