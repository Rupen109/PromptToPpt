/**
 * Full QA of "Edit with AI", nothing faked: a real browser, the real editor, the real API and the REAL model. Each case copies a deck into a fresh Gold account, opens the editor on the
 * slide the person was on (selecting the object they meant), types the prompt, lets the editor apply and save, then judges the SAVED deck (e2e/ai-full-qa-cases.mjs) and keeps a screenshot.
 *
 *   QA_DECKS=<decks.json> QA_OUT=<dir> E2E_WEB=http://localhost:3100 node e2e/ai-full-qa.mjs [CASE_ID ...]
 *
 * QA_DECKS maps a deck key to { document } (the seed decks are real people's decks, so they are NOT kept in the repo). Costs real AI calls: run it on purpose.
 * Pictures that would be GENERATED by AI are never confirmed (project rule: no AI images in tests); such a case is reported as "proposal only".
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { API, EDITOR, launch } from './lib.mjs'
import { person } from './kits-lib.mjs'
import { CASES } from './ai-full-qa-cases.mjs'
import { bgLum, layoutOf } from './ai-full-qa-lib.mjs'

const OUT = process.env.QA_OUT ?? 'e2e/results/ai-full-qa'
const DECKS = JSON.parse(readFileSync(process.env.QA_DECKS, 'utf8'))
const want = process.argv.slice(2)
const cases = CASES.filter((c) => !want.length || want.includes(c.id))
mkdirSync(`${OUT}/shots`, { recursive: true })
const FILE = `${OUT}/results.json`
const results = existsSync(FILE) ? JSON.parse(readFileSync(FILE, 'utf8')) : {}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const BOX = 'textarea[aria-label="Message to the AI assistant"]'

const b = await launch()
let A = null, used = 0
async function account() {
  if (A && used < 14) {
    const bal = (await (await A.ctx.request.get(`${API}/api/v1/me/entitlements`, { headers: { origin: EDITOR } })).json()).data?.credits?.balance ?? 0
    if (bal >= 60) return A
  }
  if (A) await A.ctx.close().catch(() => {})
  A = await person(b, 'aiqa', 'gold'); used = 0
  return A
}

async function runCase(c) {
  const A = await account(); used++
  const H = { origin: EDITOR }
  const call = (method, path, data) => A.ctx.request.fetch(`${API}/api/v1${path}`, { method, headers: H, ...(data !== undefined ? { data } : {}) })
  const balance = async () => (await (await call('GET', '/me/entitlements')).json()).data?.credits?.balance
  const made = await (await call('POST', '/presentations', { title: `QA ${c.id}` })).json()
  const id = made.data.id
  const get = async () => (await (await call('GET', `/presentations/${id}`)).json()).data
  const cur = await get()
  const seed = structuredClone(DECKS[c.deck].document)
  const doc = { ...seed, id: cur.document.id }
  c.setup?.(doc)
  if (c.prepare) await c.prepare({ A, id, doc, API })
  const put = await call('PUT', `/presentations/${id}`, { baseRevision: cur.revision, document: doc, snapshot: false })
  if (!put.ok()) throw new Error(`seed save ${put.status()} ${(await put.text()).slice(0, 300)}`)
  const p = A.p
  const pageErrors = []
  const onErr = (e) => pageErrors.push(String(e).slice(0, 200))
  p.on('pageerror', onErr)
  try {
    await p.goto(`${EDITOR}/edit/${id}`, { waitUntil: 'networkidle' })
    await p.locator('[data-testid="stage"]').waitFor({ timeout: 30000 })
    await p.getByRole('button', { name: /Edit with AI/ }).click()
    const box = p.locator(BOX)
    await box.waitFor({ timeout: 15000 })
    const enabled = (ms = 240000) => p.waitForFunction((sel) => { const m = document.querySelector(sel); return !!m && !m.disabled }, BOX, { timeout: ms })
    await enabled(20000)
    if (c.slide) { await p.locator(`[data-testid="thumb-${c.slide - 1}"]`).click(); await p.waitForTimeout(500) }
    let sel = null
    if (c.select) {
      const s = (await get()).document.slides[c.slide - 1]
      const e = c.select.id ? s.elements.find((x) => x.id === c.select.id) : s.elements.find((x) => !x.decorative && (!c.select.type || x.type === c.select.type) && (!c.select.role || x.role === c.select.role))
      sel = e?.id ?? null
      if (!sel) throw new Error(`nothing to select for ${JSON.stringify(c.select)}`)
      await p.locator(`[data-testid="stage"] [data-element="${sel}"]`).click({ force: true })
      await p.waitForTimeout(400)
    }
    const before = (await get()).document
    const turns = []
    /** waits until the saved deck stops changing (the editor applies, saves, then reports) */
    const settled = async () => { let last = -1, same = 0; for (let i = 0; i < 40 && same < 3; i++) { await sleep(1200); const r = (await get()).revision; same = r === last ? same + 1 : 0; last = r } }
    const lastShown = async () => { const chat = (await (await call('GET', `/presentations/${id}/chat`)).json()).data ?? []; const m = [...chat].reverse().find((x) => x.role !== 'user'); const bd = m ?? {}; return { role: m?.role, text: [bd.reply ?? bd.text ?? bd.error ?? '', ...(bd.applied ?? []).map((x) => '✓ ' + x), ...(bd.notes ?? []).map((x) => '• ' + x)].join('\n') } }
    const one = async (label, act) => {
      const pre = (await get()).document, bal0 = await balance()
      const respP = p.waitForResponse((r) => r.request().method() === 'POST' && /\/ai-assist$/.test(new URL(r.url()).pathname), { timeout: 240000 })
      await act()
      const resp = await respP
      let body = null; try { body = await resp.json() } catch { /* not json */ }
      const d = body?.data ?? body ?? {}
      await enabled()
      await settled()
      await sleep(1500)
      const post = (await get()).document
      const shown = await lastShown()
      const tr = { prompt: label, http: resp.status(), serverReply: d.reply ?? d.error?.message ?? JSON.stringify(body).slice(0, 300), ask: !!d.ask, options: (d.options ?? []).map((o) => o.label), proposals: (d.images ?? []).length, creditsCharged: d.creditsCharged ?? 0, upgrade: d.upgrade ?? null, shown: shown.text, shownRole: shown.role, balanceBefore: bal0, balanceAfter: await balance(), lightAfter: post.slides.filter((s) => (bgLum(post, s) ?? 0) > 170).length / post.slides.length, added: post.slides.length - pre.slides.length, layoutsAfter: post.slides.map(layoutOf) }
      turns.push(tr)
      return tr
    }
    for (const t of c.turns) {
      const text = typeof t === 'string' ? t : t.text
      const tr = await one(text, async () => { await box.fill(text); await box.press('Enter') })
      if (typeof t === 'object' && t.confirm && tr.options.length) {
        const yes = tr.options[0]
        await one(`[clicked] ${yes}`, async () => { await p.locator('button', { hasText: yes }).last().click() })
      }
    }
    const after = (await get()).document
    // screenshot: the slide the case is about
    const shotAt = c.shot === 'last' ? after.slides.length : c.shot === 'new' ? Math.max(1, after.slides.findIndex((s) => !before.slides.some((x) => x.id === s.id)) + 1) : (c.shot ?? c.slide ?? 1)
    await p.keyboard.press('Escape').catch(() => {})
    await p.locator(`[data-testid="thumb-${Math.min(shotAt, after.slides.length) - 1}"]`).click().catch(() => {})
    await p.waitForTimeout(1200)
    await p.screenshot({ path: `${OUT}/shots/${c.id}.png` })
    mkdirSync(`${OUT}/docs`, { recursive: true })
    writeFileSync(`${OUT}/docs/${c.id}.json`, JSON.stringify({ before, after }))
    const last = turns.at(-1)
    const r = { all: turns.map((x) => x.shown).join('\n'), ask: last.ask }
    let problems
    // (a check may read more from the server, e.g. the comments: it gets the account, the API and the deck id, and may be async)
    try { problems = await c.check({ b: before, a: after, r, turns, sel, A, API, id }) } catch (e) { problems = [`check crashed: ${e.message}`] }
    const claimedDone = turns.some((x) => /^Done/m.test(x.shown) || /✓/.test(x.shown))
    const proposalOnly = !!c.picture && problems.length > 0 && turns.some((x) => x.proposals > 0)
    let verdict
    if (!problems.length) verdict = c.review ? 'PASS (check) – needs visual review' : 'PROD READY'
    else if (proposalOnly) verdict = 'PROPOSAL ONLY (AI picture not generated in tests)'
    else verdict = 'NEED TO FIX'
    return { id: c.id, src: c.src, deck: c.deck, slide: c.slide, prompts: c.turns.map((t) => (typeof t === 'string' ? t : t.text)), expect: c.expect, verdict, problems, falseDone: claimedDone && problems.length > 0 && !proposalOnly, turns, pageErrors, deckId: id }
  } finally { p.off('pageerror', onErr) }
}

for (const c of cases) {
  const t0 = Date.now()
  let res
  try { res = await runCase(c) } catch (e) { res = { id: c.id, src: c.src, prompts: c.turns.map((t) => (typeof t === 'string' ? t : t.text)), verdict: 'HARNESS ERROR', problems: [String(e.message ?? e).split('\n')[0].slice(0, 300)] } }
  res.seconds = Math.round((Date.now() - t0) / 1000)
  results[c.id] = res
  writeFileSync(FILE, JSON.stringify(results, null, 2))
  console.log(`${res.verdict.padEnd(14)} ${c.id} ${res.prompts.join(' → ').slice(0, 70)}${res.problems.length ? `\n      ${res.problems.join(' | ').slice(0, 300)}` : ''}${res.turns ? `\n      AI: ${res.turns.map((x) => x.shown.replace(/\n/g, ' ')).join(' ‖ ').slice(0, 300)}` : ''}`)
}
await b.close()
