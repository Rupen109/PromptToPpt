// Measures the real width of every character the slide fonts draw, in a real browser, and writes packages/theme/src/font-widths.ts. The layout engine reads it
// to know how wide text really is (before: one average width per font, which let short bold numbers like "99.95%" wrap). Rerun when a slide font is added:
//   node scripts/gen-font-widths.mjs
// Fonts come from Google Fonts at the weights packages/ui/src/fonts.ts loads; system fonts (Arial, Georgia, ...) are measured as this machine has them.
import { readFileSync, writeFileSync } from 'node:fs'
import { launch } from '../e2e/lib.mjs'

const root = new URL('..', import.meta.url).pathname
const ui = readFileSync(`${root}packages/ui/src/fonts.ts`, 'utf8')
const metrics = readFileSync(`${root}packages/theme/src/text-metrics.ts`, 'utf8')
const families = [...new Set([...ui.matchAll(/'([A-Za-z0-9 ]+)': \[|(\b[A-Z][A-Za-z]+): \[/g)].map((m) => m[1] ?? m[2]))]
const system = ['Arial', 'Helvetica', 'Georgia', 'Times New Roman', 'Verdana']
const known = [...metrics.slice(metrics.indexOf('FONT_WIDTH'), metrics.indexOf('DEFAULT_WIDTH')).matchAll(/'?([A-Za-z0-9 ]+)'?: 0\./g)].map((m) => m[1].trim())
const missing = known.filter((f) => !families.includes(f) && !system.includes(f) && f !== 'Calibri')
if (missing.length) throw new Error(`fonts in FONT_WIDTH but not loaded by packages/ui/src/fonts.ts: ${missing.join(', ')}`)
const WEIGHTS = [300, 400, 500, 600, 700, 800, 900] // every weight the slide fonts ship (designs draw headings and figures from 300 to 900)
const GLYPHS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('') + '–—‘’“”…•·€£₹×'

const b = await launch()
const p = await b.newPage()
const href = `https://fonts.googleapis.com/css2?${families.map((f) => `family=${f.replace(/ /g, '+')}:wght@${(ui.match(new RegExp(`'?${f}'?: \\[([^\\]]+)\\]`))?.[1] ?? '400;700').replace(/,\s*/g, ';')}`).join('&')}&display=block`
await p.setContent(`<link rel="stylesheet" href="${href}">`, { waitUntil: 'networkidle' })
const table = await p.evaluate(async ({ families, system, WEIGHTS, GLYPHS }) => {
  const out = {}
  const ctx = document.createElement('canvas').getContext('2d')
  for (const f of [...families, ...system]) {
    out[f] = {}
    for (const w of WEIGHTS) {
      if (!system.includes(f)) await document.fonts.load(`${w} 100px "${f}"`, GLYPHS)
      if (!system.includes(f) && !document.fonts.check(`${w} 100px "${f}"`, GLYPHS)) throw new Error(`${f} ${w} did not load`)
      ctx.font = `${w} 1000px "${f}", monospace`
      // two base-36 characters per width (0–1295 thousandths of the size): compact, and still exact to 0.1%
      out[f][w] = [...GLYPHS].map((ch) => Math.min(1295, Math.round(ctx.measureText(ch).width)).toString(36).padStart(2, '0')).join('')
    }
  }
  return out
}, { families, system, WEIGHTS, GLYPHS })
await b.close()

// sanity: a font that did not load would measure as the monospace fallback (every glyph the same width)
for (const [f, ws] of Object.entries(table)) if (new Set(ws[400].match(/../g)).size < 10 && !/Mono/.test(f)) throw new Error(`${f}: widths look like a fallback font`)

writeFileSync(`${root}packages/theme/src/font-widths.ts`, `// GENERATED by scripts/gen-font-widths.mjs: the advance width of each character, in thousandths of the font size, per font and weight, measured in a browser.
// Do not edit by hand; rerun the script when a slide font is added.

/** the characters measured, in table order */
export const GLYPHS = ${JSON.stringify(GLYPHS)}
/** the weights measured (others use the nearest) */
export const WEIGHTS = ${JSON.stringify(WEIGHTS)} as const
/** font → weight → widths, two base-36 characters each, one per GLYPHS character */
export const FONT_ADVANCES: Record<string, Record<number, string>> = ${JSON.stringify(table, null, 1)}
`)
console.log(`font widths: ${Object.keys(table).length} fonts × ${WEIGHTS.length} weights × ${GLYPHS.length} characters`)
