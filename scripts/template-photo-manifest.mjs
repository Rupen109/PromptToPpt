// Writes packages/theme/src/templates/photos.generated.ts from the pictures that really exist in apps/web/public/template-assets,
// so decks never point at a picture that failed to generate. Run after template-images.ts (the optimise script does).
import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const root = new URL('..', import.meta.url)
const keys = readdirSync(fileURLToPath(new URL('apps/web/public/template-assets/', root))).filter((f) => /^[a-z-]+-\d+\.jpg$/.test(f)).map((f) => f.replace(/\.jpg$/, '')).sort()
writeFileSync(fileURLToPath(new URL('packages/theme/src/templates/photos.generated.ts', root)), `// GENERATED by scripts/template-photo-manifest.mjs — do not edit.\nexport const AVAILABLE_PHOTOS: readonly string[] = ${JSON.stringify(keys)}\n`)
console.log(`${keys.length} template pictures listed`)
